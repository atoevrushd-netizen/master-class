  function hasLang(lang) {
    return typeof lang === "string" && Object.prototype.hasOwnProperty.call(I18N, lang);
  }

  function applyLang(lang, persist) {
    if (!hasLang(lang)) lang = DEFAULT_LANG;
    var t = I18N[lang];
    var root = document.documentElement;
    root.lang = lang;
    root.setAttribute("data-lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = t[el.getAttribute("data-i18n")];
      if (value !== undefined) el.textContent = value;
    });

    /* data-i18n-attr="aria-label:key;title:key2" */
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split(";").forEach(function (pair) {
        var parts = pair.split(":");
        var value = t[(parts[1] || "").trim()];
        if (parts[0] && value !== undefined) el.setAttribute(parts[0].trim(), value);
      });
    });

    document.title = t.doc_title;
    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute("content", t.meta_desc);

    document.querySelectorAll("[data-set-lang]").forEach(function (btn) {
      var active = btn.getAttribute("data-set-lang") === lang;
      btn.classList.toggle("is-active", active);
      btn.setAttribute("aria-pressed", active ? "true" : "false");
    });

    var waUrl = "https://wa.me/" + WA_NUMBER + "?text=" + encodeURIComponent(t.cta_wa_message);
    document.querySelectorAll("a[data-cta]").forEach(function (cta) {
      cta.setAttribute("href", waUrl);
      cta.setAttribute("aria-label", t.cta_aria);
    });

    if (persist) {
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    }
  }

  function initialLang() {
    var fromUrl = (new URLSearchParams(window.location.search).get("lang") || "").toLowerCase();
    if (hasLang(fromUrl)) return fromUrl;
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (hasLang(stored)) return stored;
    } catch (e) {}
    return DEFAULT_LANG;
  }

  applyLang(initialLang(), false);

  document.querySelectorAll("[data-set-lang]").forEach(function (btn) {
    btn.addEventListener("click", function () {
      var lang = btn.getAttribute("data-set-lang");
      applyLang(lang, true);
      /* Keep an explicit ?lang= in the URL in sync with the choice */
      try {
        var url = new URL(window.location.href);
        if (url.searchParams.has("lang")) {
          url.searchParams.set("lang", lang);
          history.replaceState(null, "", url.toString());
        }
      } catch (e) {}
    });
  });
